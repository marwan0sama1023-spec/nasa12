  function apply(root = document.body) {
    if (!root || ![Node.ELEMENT_NODE, Node.DOCUMENT_NODE].includes(root.nodeType)) root = document.body;
    mutationObserver?.disconnect();
    const english = language === "en";
    document.documentElement.lang = english ? "en" : "ar";
    document.documentElement.dir = english ? "ltr" : "rtl";
    document.title = english ? "Planetary Exploration | Planetary Environments" : "استكشاف الكواكب | البيئات الكوكبية";
    const description = document.querySelector('meta[name="description"]');
    if (description) description.content = english
      ? "Planetary Exploration — An interactive science experience exploring Earth environments that offer specific comparisons to lunar and Martian terrain, using NASA information and imagery."
      : "منصة علمية تفاعلية لاستكشاف البيئات الأرضية الشبيهة بالقمر والمريخ بالاستناد إلى معلومات وصور NASA.";
    document.body.classList.toggle("english-ui", english);

    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
    let node;
    while ((node = walker.nextNode())) {
      if (!originalText.has(node)) originalText.set(node, node.nodeValue);
      const original = originalText.get(node);
      const translated = localizeValue(original);
      if (node.nodeValue !== translated) node.nodeValue = translated;
    }

    const explicitTranslations = [];
    if (root.matches?.("[data-i18n-en]")) explicitTranslations.push(root);
    root.querySelectorAll?.("[data-i18n-en]").forEach(element => explicitTranslations.push(element));
    explicitTranslations.forEach(element => {
      const localized = english ? element.dataset.i18nEn : element.dataset.i18nAr;
      if (localized !== undefined && element.textContent !== localized) element.textContent = localized;
    });

    const attributeNames = ["aria-label", "title", "placeholder", "alt"];
    const attributeElements = [];
    if (root.nodeType === Node.ELEMENT_NODE && attributeNames.some(name => root.hasAttribute(name))) attributeElements.push(root);
    root.querySelectorAll?.("[aria-label], [title], [placeholder], [alt]").forEach(element => attributeElements.push(element));
    attributeElements.forEach(element => {
      let saved = originalAttributes.get(element);
      if (!saved) {
        saved = {};
        originalAttributes.set(element, saved);
      }
      attributeNames.forEach(name => {
        if (!element.hasAttribute(name)) return;
        if (!(name in saved)) saved[name] = element.getAttribute(name);
        const original = saved[name];
        const translated = localizeValue(original);
        if (element.getAttribute(name) !== translated) element.setAttribute(name, translated);
      });
    });

    document.querySelectorAll(".language-toggle").forEach(button => {
      button.textContent = english ? "Arabic" : "English";
      button.setAttribute("aria-label", english ? "Switch to Arabic" : "Switch to English");
      button.title = english ? "Switch to Arabic" : "Switch to English";
    });

    if (document.body) {
      mutationObserver ||= new MutationObserver(records => {
        records.forEach(record => {
          if (record.type === "childList") record.addedNodes.forEach(added => {
            if (added.nodeType === Node.ELEMENT_NODE) apply(added);
            else if (added.nodeType === Node.TEXT_NODE && added.parentElement) apply(added.parentElement);
          });
          if (record.type === "characterData") apply(record.target.parentElement || document.body);
          if (record.type === "attributes") apply(record.target);
        });
      });
      mutationObserver.observe(document.body, { childList: true, characterData: true, attributes: true, subtree: true });
    }
  }

  function toggle() {
    language = language === "en" ? "ar" : "en";
    localStorage.setItem(languageKey, JSON.stringify(language));
    apply(document.body);
    window.dispatchEvent(new CustomEvent("site-language-change", { detail: { language } }));
    return language;
  }

  window.siteI18n = { apply, toggle, translateValue, localizeValue, get language() { return language; } };
